def parse_cases():
    cases = OrderedDict()
    for d in CASE_DIRS:
        for f in sorted(d.glob("*.md")):
            for cid, title in CASE_RE.findall(f.read_text(encoding="utf-8")):
                cases[cid] = (f.relative_to(ROOT).as_posix(), title.strip())
    return cases


def build(check_only: bool = False) -> int:
    cases = parse_cases()
    known = set(cases)
    errors = []

    # 需求点自身唯一
    ids = [r[0] for r in REQS]
    dup = [k for k, v in Counter(ids).items() if v > 1]
    if dup:
        errors.append(f"需求点 ID 重复：{dup}")

    referenced = set()
    rows = []
    for rid, sec, summary, phase, csl in REQS:
        cl = [c.strip() for c in csl.split(",") if c.strip()]
        missing = [c for c in cl if c not in known]
        if missing:
            errors.append(f"{rid} 引用了不存在的 case：{missing}")
        if not cl:
            errors.append(f"{rid} 未承接任何 case（{summary}）")
        referenced.update(cl)
        rows.append((rid, sec, summary, phase, cl))

    orphan = sorted(known - referenced)
    if orphan:
        errors.append(f"以下 case 未被任何需求点引用：{orphan}")

    total_r = len(REQS)
    covered = sum(1 for r in rows if r[4])
    oc = Counter(r[3] for r in rows)

    if not check_only:
        out = []
        out.append("# P1 需求点清单（需求基线）\n")
        out.append("> **本文件回答一个问题：PRD 的每一条规则，有没有 case 承接。**")
        out.append("> 这是「case 是需求基线、不是代码镜像」的落地物：需求点来自 `docs/prd-homecube.md` 的**规则级条目**，不以接口为粒度——")
        out.append("> 接口只覆盖「有什么口」，覆盖不了「必须满足什么约束」（如 50 格权限矩阵、四类冲突策略、四个降级词、导出排除 L3）。")
        out.append("> 生成器：`python3 docs/cases/gen_requirements.py`；校验：`--check`（G-F 门禁）。**手改本文件无效，以生成器为准。**\n")
        out.append(f"**统计**：需求点 {total_r} 条 · 全部有 case 承接（{covered}/{total_r}）· 承接 case {len(referenced)} 条 · 模块 case 总数 {len(known)} 条\n")
        out.append("**期次分布**：" + " / ".join(f"{k} {v}" for k, v in oc.most_common()) + "\n")
        out.append("> 期次口径取 PRD 原文；`未点名(P1-Mx)` 表示 PRD 明确了期但技术方案 §十一 的 Sprint 表未点名该能力，")
        out.append("> 属「有期无 Sprint」，须在排期时补位，不得当作无期项。\n")

        groups = OrderedDict()
        for rid, sec, summary, phase, cl in rows:
            ch = sec.split(":")[0]
            top = ch.split(".")[0]
            groups.setdefault(top, []).append((rid, sec, summary, phase, cl))

        titles = {
            "3": "第三章 HomeOS（3.2 边界与结构 / 3.3 职责 / 3.4 详细需求 / 3.5 交互 / 3.6 数据模型 / 3.7 接口 / 3.8 补充验收）",
            "4": "第四章 财务系统（4.2 工程约定 / 4.5 详细需求 / 4.7 数据模型 / 4.8 接口 / 4.9 验收标准）",
            "5": "第五章 日历系统（5.2 边界 / 5.5 详细需求 / 5.7 数据模型 / 5.8 接口 / 5.9 验收，㉚ 新增的业务面）",
            "11": "第十一章 系统间接口与事件规范",
            "12": "第十二章 迭代规划与 Agent 推进机制",
            "13": "第十三章 非功能需求",
            "15": "第十五章 建设边界与资产关系（交付清单 / 范围外 / 工程约定）",
            "16": "第十六章 权限与角色矩阵",
            "17": "第十七章 数据归属权威表与跨面契约",
            "18": "第十八章 面导航与信息架构",
            "19": "第十九章 验收口径（19.2 底座与跨面 / 19.3 财务面 / 19.4 日历面 / 19.7 对账）",
            "20": "第二十章 外部依赖清单（埋点字典）",
            "21": "第二十一章 数据分级与安全合规",
            "22": "第二十二章 非功能需求补充",
            "23": "第二十三章 技术约束与研发流程载体（架构红线 + CI/CD 门禁，自第一行代码起生效）",
        }
        for top, items in groups.items():
            out.append(f"\n## {titles.get(top, top)}\n")
            out.append("| 需求点 | 章节:行 | 需求要点 | 期次 | 承接 case |")
            out.append("|---|---|---|---|---|")
            for rid, sec, summary, phase, cl in items:
                cs = "、".join(cl) if cl else "**未承接**"
                out.append(f"| `{rid}` | {sec} | {summary} | {phase} | {cs} |")
        out.append("\n---\n")
        out.append("## 未登记为需求点的 PRD 章节（及理由）\n")
        out.append("明确写出「不登记」比默默略过安全——否则下一轮审核会把它们当成遗漏重新翻一遍，或更糟：被当成「没有要求」。\n")
        out.append("| PRD 章节 | 内容 | 为什么不登记 |")
        out.append("|---|---|---|")
        out.append("| 3.1 / 4.1 / 4.3 与 6-10 章的定位与职责叙述 | 系统定位、系统职责、P2+ 各面 | 叙述性，无判定口径。第五章（日历）的规则与接口已登记为需求点（R-342-*、R-55x-*、R-194-*）；P2+ 五面（采购/饮食/出行/家人/成长）随出生期立 case，不进 P1 分母 |")
        out.append("| 3.4.7 / 4.5 中的 P2-P6 能力 | 规则引擎、AI 归类、多币种、投资理财等 | 期次不在 P1，登记会稀释 P1 覆盖率分母。个别需 P1 就守住的**负向边界**已单独立 case（HOM-ARCH-008/024） |")
        out.append("| 12.x 迭代规划与 Agent 机制 | 六期路线、看板、租约、人工审核粒度 | 属研发流程治理，不是产品验收对象。其中「期次划分」已作为每条需求点的期次依据被消费 |")
        out.append("| 19.x 验收口径表 | 19.1-19.3、19.5-19.8 的判定方法 | **判定口径**（怎么测）而非需求条目（测什么），统一在 `crosscutting/acceptance-19.2-19.3.md` 维护，避免两处漂移；其中 **19.4 日历面七条例外**——它是新增面的唯一判据来源，已逐条登记为 R-194-01..07 并各挂 case |")
        out.append("| 23.3 / 24.x 文档与流程治理 | Jarvis 看板映射、文档唯一性、审批 | 流程治理约定，由研发流程载体执行；其中可验收部分已落在 23.2 的架构红线里 |")
        out.append("| 21.3 跨期两条 | 儿童数据不参与 AI 训练、分享默认脱敏 | 承接面在 P4（家人）/P5（成长），P1 只判同意链路。已登记 `SPEC-GAP-07` 跟踪期次 |")
        out.append("\n## 使用约定\n")
        out.append("1. **新增 case 必须挂到需求点**：否则 `--check` 报「未被任何需求点引用」。")
        out.append("2. **需求点未承接即阻断**：`--check` 退出码非 0，不得以「暂不测」结案（19.1「不可测即阻断」）。")
        out.append("3. **判据写不出来时**：不改需求点、不删 case，写进 `BACKLOG.md` 的 SPEC-GAP 并注明缺哪条口径。")
        out.append("4. **PRD 变更时**：先改本文件的生成器（`REQS`），再改 case——需求先行，case 跟随。")
        (ROOT / "requirements.md").write_text("\n".join(out) + "\n", encoding="utf-8")

    if errors:
        print(f"[FAIL] 需求点校验未通过，共 {len(errors)} 项：")
        for e in errors:
            print("  -", e)
        return 1

    print(f"[OK] 需求点 {total_r} 条全部有 case 承接；case {len(known)} 条全部挂到需求点；无幽灵引用。")
    return 0


if __name__ == "__main__":
    sys.exit(build(check_only="--check" in sys.argv))
