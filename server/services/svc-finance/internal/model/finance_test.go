func TestSoftDelete(t *testing.T) {
	db := setupTestDB(t)

	// Create an account
	account := &model.FinanceAccount{
		FamilyID: "test-family-001",
		Name:     "To Be Deleted",
		Type:     "cash",
		Balance:  0,
		Version:  1,
	}

	result := db.Create(account)
	if result.Error != nil {
		t.Fatalf("failed to create account: %v", result.Error)
	}

	// Soft delete the account
	result = db.Where("id = ?", account.ID).Delete(account)
	if result.Error != nil {
		t.Fatalf("failed to soft delete account: %v", result.Error)
	}

	// Verify it's not returned in normal queries
	var count int64
	db.Model(&model.FinanceAccount{}).Where("family_id = ?", "test-family-001").Count(&count)
	if count != 0 {
		t.Errorf("expected 0 active accounts after soft delete, got %d", count)
	}

	// Verify it still exists with deleted_at set
	var deletedAccount model.FinanceAccount
	result = db.Unscoped().First(&deletedAccount, "id = ?", account.ID)
	if result.Error != nil {
		t.Fatalf("failed to retrieve soft-deleted account: %v", result.Error)
	}

	if deletedAccount.DeletedAt.Valid == false {
		t.Error("expected deleted_at to be set")
	}
}
