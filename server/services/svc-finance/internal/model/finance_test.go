package model_test

import (
	"testing"
	"time"

	"github.com/xueshuaihui/HomeCube/server/services/svc-finance/internal/model"
	"gorm.io/driver/sqlite"
	"gorm.io/gorm"
)

// setupTestDB creates an in-memory SQLite database and auto-migrates all finance models.
func setupTestDB(t *testing.T) *gorm.DB {
	t.Helper()

	// Set table prefix to empty for SQLite testing
	model.TablePrefix = ""

	db, err := gorm.Open(sqlite.Open(":memory:"), &gorm.Config{})
	if err != nil {
		t.Fatalf("failed to open test database: %v", err)
	}

	// Migrate all finance models
	err = db.AutoMigrate(
		&model.FinanceAccount{},
		&model.FinanceCategory{},
		&model.FinanceTransaction{},
		&model.FinanceLedger{},
	)
	if err != nil {
		t.Fatalf("failed to migrate models: %v", err)
	}

	return db
}

func TestFinanceAccountModel(t *testing.T) {
	db := setupTestDB(t)

	// Test creating an account
	account := &model.FinanceAccount{
		FamilyID: "test-family-001",
		Name:     "Test Account",
		Type:     "bank",
		Balance:  100000, // $1000.00 in cents
		Version:  1,
	}

	result := db.Create(account)
	if result.Error != nil {
		t.Fatalf("failed to create account: %v", result.Error)
	}

	// Note: ID is not auto-generated in tests; it's generated by the repo layer in production

	// Test retrieving the account
	var retrieved model.FinanceAccount
	result = db.First(&retrieved, "id = ?", account.ID)
	if result.Error != nil {
		t.Fatalf("failed to retrieve account: %v", result.Error)
	}

	if retrieved.Name != account.Name {
		t.Errorf("expected name %s, got %s", account.Name, retrieved.Name)
	}

	if retrieved.Balance != account.Balance {
		t.Errorf("expected balance %d, got %d", account.Balance, retrieved.Balance)
	}

	// Test TableName method
	expectedTable := "finance_account"
	if account.TableName() != expectedTable {
		t.Errorf("expected table name %s, got %s", expectedTable, account.TableName())
	}
}

