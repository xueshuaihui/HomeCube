// 生成物：deploy/nginx.unborn.conf —— 未出生面的 /api/{code}/ 前缀清单（Nginx 片段）。
//
// 为什么必须生成而不是手抄：docs/p1-tech-plan.md §1.3 把 registry.Domains() 定为「唯一真源」，
// §1.1 又要求「未出生面的 /api/{code}/ 前缀由 Nginx 直接返回『即将上线』」。这两个集合的权威源
// 只有 Go 那张表；nginx.conf 里手抄一份 code 清单就是 §1.3 明令禁止的第二真源（P2 面出生时
// 表变了、抄本没变，nginx 会继续替一个已经出生的面兜「即将上线」，而这是 18.2#9 那类断言查的形态）。
// server/packages/registry/cmd/registryd/main.go 的文件头把「the nginx/compose generation of
// S1-D」列为它的存在理由之一，本脚本就是那条消费路径。
//
// 逐值来源（本脚本不做任何判定，判定全在 Go 表里）：
//   · 哪些 code 属未出生 —— registryd --format=meta 的 unborn 数组（= registry.Unborn()，
//     即 BirthPhase > CurrentPhase；不在这里重算出生期模型，见 registry.go「Birth phase is a
//     three-state model」一节，实建标记与出生期集合只在当期偶然相等，重算即第二真源）。
//   · 每个 code 的前缀字面量 —— registryd --format=json 的 routePrefix 单元格
//     （= Domain.RoutePrefix，PREFIX 形态 /api/{code}/，registry.go 的 Domain 注释已说明
//     nginx 用的是这一形态而非 RoutePrefixGlob()）。本脚本不拼 "/api/" + code。
//
// 只写前缀，不写文案：「即将上线」这个响应体在 deploy/nginx.conf 的 @hc_unborn 里写一次
// （用词权威源 PRD 17.7 第 2 条 / 定版 ㉙ 的四词分工），本片段每行 return 418 由 error_page
// 归并到它。这样改文案不必重生成、改面集合不必碰 nginx.conf。
//
// 产物纪律与 web/generated/domains.json 同一条（见 web/scripts/gen-domains.mjs 文件头）：
// 文件进版本库、每次现取现覆写、内容逐值不改写且不加时间戳，因此可字节比对。
//
// 用法：node deploy/gen-nginx-unborn.mjs   （make up 的 [up 1/5] 步就是它）
// 环境覆盖：HC_GO=/path/to/go 指定 go 可执行文件；
//           HC_REGISTRYD_BIN=/path/to/registryd 用预构建二进制（跳过 go run）。
import { execFileSync } from 'node:child_process'
import { existsSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const DEPLOY_DIR = dirname(fileURLToPath(import.meta.url))
const REPO_DIR = resolve(DEPLOY_DIR, '..')
// server/ 是 monorepo 里唯一的 Go module（PRD 22.4），registryd 在它里面。
const SERVER_DIR = process.env.HC_SERVER_DIR || join(REPO_DIR, 'server')
const OUT = join(DEPLOY_DIR, 'nginx.unborn.conf')

function goCmd() {
  const fromEnv = process.env.HC_GO
  if (fromEnv) return fromEnv
  const sdk = join(homedir(), 'sdk', 'go', 'bin', 'go')
  return existsSync(sdk) ? sdk : 'go'
}

function registryExport(format) {
  const prebuilt = process.env.HC_REGISTRYD_BIN
  const cmd = prebuilt || goCmd()
  const args = prebuilt
    ? [`--format=${format}`]
    : ['-C', SERVER_DIR, 'run', './packages/registry/cmd/registryd', `--format=${format}`]
  try {
    return execFileSync(cmd, args, {
      encoding: 'utf8',
      env: { ...process.env, GOTOOLCHAIN: 'local' },
      maxBuffer: 8 * 1024 * 1024,
    })
  } catch (err) {
    const detail = (err.stderr || err.message || '').toString().trim()
    throw new Error(
      `调用 registryd 失败（--format=${format}）：${cmd} ${args.join(' ')}\n${detail}\n` +
        '可用 HC_GO=/path/to/go 指定 go，或 HC_REGISTRYD_BIN=/path/to/registryd 指定预构建二进制。',
    )
  }
}

// meta.unborn 给集合，json 全表给前缀；两者的顺序都按 registry 登记序（registry.go
// 「Order is a contract」），所以产物里的 location 顺序 = 首页服务矩阵的顺序。
const meta = JSON.parse(registryExport('meta'))
const table = JSON.parse(registryExport('json'))
const prefixByCode = new Map(table.map((row) => [row.code, row.routePrefix]))

const lines = []
for (const code of meta.unborn) {
  const prefix = prefixByCode.get(code)
  if (!prefix) {
    throw new Error(`registryd --format=json 的表里没有 code ${code}，无法取它的 routePrefix`)
  }
  lines.push(`  location ${prefix} { return 418; }`)
}

const header = [
  '# GENERATED BY deploy/gen-nginx-unborn.mjs —— 不要手改，改 registry 表后重跑（make up 会自动跑）。',
  `# 逐值来源：registryd --format=meta 的 unborn 集合（registry.Unborn()，BirthPhase > 当期 ${meta.currentPhase}）`,
  '#           + registryd --format=json 的 routePrefix 单元格；顺序为 registry 登记序（PRD 17.1）。',
  '# 每行 return 418 由 deploy/nginx.conf 的 error_page 归并到 @hc_unborn，响应体在那里（「即将上线」）。',
  '',
]

const body = lines.length > 0 ? `${lines.join('\n')}\n` : '  # 当期无未出生面（registry.Unborn() 为空集）\n'
writeFileSync(OUT, `${header.join('\n')}${body}`, 'utf8')

console.log(
  `gen:nginx-unborn -> deploy/nginx.unborn.conf（currentPhase=${meta.currentPhase}, ` +
    `unborn=[${meta.unborn.join(', ')}]）`,
)
